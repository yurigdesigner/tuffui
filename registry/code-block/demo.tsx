"use client";

import { CodeBlock } from "./code-block";

const short = `import { createCache } from "./cache";

// Resized images are keyed by content hash, so a changed file always misses.
export async function resize(src: string, width: number) {
  const key = await hash(src, width);
  const hit = await cache.get(key);
  if (hit) return hit;
  return cache.set(key, await sharp(src).resize(width).toBuffer());
}`;

const long = Array.from(
  { length: 6 },
  (_, i) => `export const route${i} = defineRoute({
  path: "/blog/post-${i + 1}",
  image: { width: ${640 + i * 160}, format: "avif" },
  revalidate: ${(i + 1) * 60},
});
`,
).join("\n");

export default function CodeBlockDemo({ variant }: { variant?: string }) {
  if (variant === "Long") {
    return (
      <CodeBlock
        className="max-w-xl"
        data={{
          code: `// Generated by pressd routes\n${long}`,
          language: "ts",
          filename: "routes.gen.ts",
        }}
        collapseAfter={12}
      />
    );
  }
  return (
    <CodeBlock
      className="max-w-xl"
      data={{
        code: short,
        language: "ts",
        filename: "src/site/images.ts",
        highlight: [5, 6, 7],
      }}
    />
  );
}
